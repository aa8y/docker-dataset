"""Unit tests for cockroach/scripts/employees/transform.

The dump -> CSV half of this hook is shared byte for byte with
duckdb/scripts/employees/transform (Docker build contexts cannot reach across
engines, so the block is duplicated rather than imported). test_duckdb_employees
covers that parser in detail; the first test here is what keeps the two copies
from drifting, and the rest cover what is specific to CockroachDB: the schema
keeps its foreign keys, and the data is loaded with IMPORT INTO from the node's
external-IO dir rather than COPY.
"""
import shutil
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = Path(__file__).parent / "fixtures" / "employees"

MARKER = "# " + "-" * 75


def shared_block(path):
    """The hook's shared section: everything between the two banner comments."""
    text = path.read_text(encoding="utf-8")
    start = text.index(MARKER)
    end = text.index("# End of the shared block.")
    return text[start:end]


# --- the duplicated block ---------------------------------------------------

def test_shared_block_is_identical_in_both_hooks():
    # Both engines load employees from per-table CSVs and need the same
    # dump -> CSV conversion, but each is its own Docker build context, so the
    # code is duplicated verbatim. Drift between the copies would show up as
    # two engines disagreeing about the data, which no other test would catch.
    cockroach = shared_block(ROOT / "cockroach/scripts/employees/transform")
    duckdb = shared_block(ROOT / "duckdb/scripts/employees/transform")
    assert cockroach == duckdb
    # Guard the extraction itself: an empty or truncated block would make the
    # comparison above pass for the wrong reason.
    assert "def dump_to_csv(" in cockroach
    assert "def table_columns(" in cockroach
    assert "def write_csvs(" in cockroach


# --- stage_schema -----------------------------------------------------------

def test_stage_schema_keeps_everything_but_the_database_management(
        cockroach_employees, monkeypatch):
    monkeypatch.chdir(FIXTURES)
    ddl = cockroach_employees.stage_schema()
    # The entrypoint creates COCKROACH_DATABASE and runs this script inside it.
    assert "DROP DATABASE" not in ddl
    assert "CREATE DATABASE" not in ddl
    assert "\\connect" not in ddl
    # Nothing to reset on the database the entrypoint just created.
    assert "DROP TABLE" not in ddl
    # Everything else is upstream's, foreign keys included -- IMPORT INTO
    # leaves them unvalidated rather than refusing the load.
    assert ddl.count("CREATE TABLE ") == 6
    assert ddl.count("CREATE OR REPLACE VIEW ") == 2
    assert ddl.count("FOREIGN KEY ") == 6
    assert ddl.count("ON DELETE CASCADE") == 6
    assert "CHECK (gender IN ('M','F'))" in ddl


# --- main() -----------------------------------------------------------------

def test_main_exits_when_a_dump_is_missing(
        cockroach_employees, tmp_path, monkeypatch):
    shutil.copytree(FIXTURES / "test_db", tmp_path / "test_db")
    (tmp_path / "test_db" / "load_salaries2.dump").unlink()
    monkeypatch.chdir(tmp_path)
    with pytest.raises(SystemExit):
        cockroach_employees.main()


def test_golden_bundle(cockroach_employees, tmp_path, monkeypatch):
    # The expected/ files were generated by this hook from the fixture clone
    # and read through before committing. The CSVs are the same bytes the
    # duckdb hook produces, so both engines assert against one shared copy.
    shutil.copytree(FIXTURES / "test_db", tmp_path / "test_db")
    monkeypatch.chdir(tmp_path)
    cockroach_employees.main()

    assert (tmp_path / "employees.sql").read_text(encoding="utf-8") == \
        (FIXTURES / "expected" / "cockroach" / "employees.sql").read_text(
            encoding="utf-8")
    for csv_file in sorted((FIXTURES / "expected" / "csv").iterdir()):
        assert (tmp_path / csv_file.name).read_bytes() == \
            csv_file.read_bytes(), csv_file.name


def test_import_statements_run_in_dependency_order(cockroach_employees,
                                                   tmp_path, monkeypatch):
    # departments and employees are the FK targets, so they must be imported
    # before the three tables that reference them.
    shutil.copytree(FIXTURES / "test_db", tmp_path / "test_db")
    monkeypatch.chdir(tmp_path)
    cockroach_employees.main()
    imports = [line.split()[2] for line
               in (tmp_path / "employees.sql").read_text(
                   encoding="utf-8").splitlines()
               if line.startswith("IMPORT INTO ")]
    assert imports == ["departments", "employees", "dept_emp", "dept_manager",
                       "titles", "salaries"]


def test_every_import_reads_from_the_external_io_dir(cockroach_employees,
                                                     tmp_path, monkeypatch):
    # The load hook moves the CSVs to /csv, which the final image pins as the
    # node's --external-io-dir, so every source must be a bare
    # `nodelocal://1/<table>.csv`.
    shutil.copytree(FIXTURES / "test_db", tmp_path / "test_db")
    monkeypatch.chdir(tmp_path)
    cockroach_employees.main()
    sql = (tmp_path / "employees.sql").read_text(encoding="utf-8")
    for table, _ in cockroach_employees.DUMPS:
        assert ("CSV DATA ('nodelocal://1/{}.csv') WITH nullif = '';"
                .format(table)) in sql

"""Unit tests for cockroach/scripts/moma/transform.

MoMA ships only CSV, so the schema is authored in the repo (schema.sql) and this
hook parses it to build the IMPORT column list, then normalizes each raw export
into a CSV whose rows match that list positionally. Two things can go wrong
quietly: the parser drifting from the schema (rows would load into the wrong
columns, not fail), and the CSV normalization mangling MoMA's embedded newlines
and quotes. The first test therefore reads the *real* schema.sql, not a fixture.
"""
import shutil
from pathlib import Path

import pytest

FIXTURES = Path(__file__).parent / "fixtures" / "moma"
SCHEMA = Path(__file__).resolve().parents[2] / "cockroach/scripts/moma/schema.sql"


# --- table_columns, against the real schema --------------------------------

def test_table_columns_matches_real_schema(moma):
    # Parsed against cockroach/scripts/moma/schema.sql itself, so a schema edit
    # the parser cannot handle (a constraint line, a reflowed definition) fails
    # here rather than loading MoMA's data into shifted columns.
    ddl = SCHEMA.read_text(encoding="utf-8")
    assert moma.table_columns(ddl, "artists") == [
        "constituent_id", "display_name", "artist_bio", "nationality", "gender",
        "begin_date", "end_date", "wiki_qid", "ulan",
    ]
    artworks = moma.table_columns(ddl, "artworks")
    assert len(artworks) == 30
    assert artworks[:3] == ["title", "artist", "constituent_id"]
    assert artworks[-1] == "duration_sec"
    # Every entry must be a bare column name: a constraint or a reflowed
    # definition would leave punctuation or an uppercase keyword behind.
    for col in artworks + moma.table_columns(ddl, "artists"):
        assert col.replace("_", "").isalnum() and col.islower(), col


def test_every_csv_table_is_in_the_real_schema(moma):
    # CSV_TABLES and schema.sql must name the same tables.
    ddl = SCHEMA.read_text(encoding="utf-8")
    for _, table in moma.CSV_TABLES:
        assert moma.table_columns(ddl, table)


def test_table_columns_exits_on_missing_table(moma):
    with pytest.raises(SystemExit):
        moma.table_columns("CREATE TABLE artists (\n  a text\n);\n", "artworks")


# --- normalize_csv ----------------------------------------------------------

def test_normalize_csv_skips_header_and_fits_rows_to_width(moma, tmp_path):
    src, dst = tmp_path / "in.csv", tmp_path / "out.csv"
    src.write_text("H1,H2,H3\n"      # header, dropped
                   "a,b,c\n"          # exact width
                   "d\n"              # short -> padded with empty cells
                   "e,f,g,h,i\n",     # long  -> truncated
                   encoding="utf-8")
    moma.normalize_csv(str(src), 3, str(dst))
    # Padded cells are written unquoted, so IMPORT's `nullif = ''` reads them
    # as NULL.
    assert dst.read_text(encoding="utf-8") == "a,b,c\nd,,\ne,f,g\n"


def test_normalize_csv_round_trips_newlines_and_quotes(moma, tmp_path):
    src, dst = tmp_path / "in.csv", tmp_path / "out.csv"
    src.write_text('H1,H2\n"multi\nline","he said ""hi"""\n', encoding="utf-8")
    moma.normalize_csv(str(src), 2, str(dst))
    assert dst.read_text(encoding="utf-8") == \
        '"multi\nline","he said ""hi"""\n'


# --- main() -----------------------------------------------------------------

def test_main_exits_when_an_export_is_missing(moma, tmp_path, monkeypatch):
    monkeypatch.setattr(moma, "SCHEMA", str(FIXTURES / "schema.sql"))
    monkeypatch.setattr(moma, "CSV_DIR", str(tmp_path / "csv"))
    monkeypatch.chdir(tmp_path)
    with pytest.raises(SystemExit):
        moma.main()


def test_golden_bundle(moma, tmp_path, monkeypatch):
    # The expected/ files were generated by this hook from input/ + schema.sql
    # and read through before committing. SCHEMA and CSV_DIR are absolute paths
    # into the image, and CSV_DIR is bound at import, so both are patched on the
    # module rather than via the environment.
    for name in ("Artists.csv", "Artworks.csv"):
        shutil.copy(FIXTURES / "input" / name, tmp_path / name)
    csv_dir = tmp_path / "csv"
    monkeypatch.setattr(moma, "SCHEMA", str(FIXTURES / "schema.sql"))
    monkeypatch.setattr(moma, "CSV_DIR", str(csv_dir))
    monkeypatch.chdir(tmp_path)
    moma.main()

    expected = FIXTURES / "expected"
    assert (tmp_path / "moma.sql").read_text(encoding="utf-8") == \
        (expected / "moma.sql").read_text(encoding="utf-8")
    for name in ("artists.csv", "artworks.csv"):
        assert (csv_dir / name).read_bytes() == (expected / name).read_bytes(), name
